import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const vendor = new URL("../", import.meta.url);
const source = (path) => fileURLToPath(new URL(path, vendor));
const bundle = await build({
  stdin: {
    contents: `export { SHAPES } from ${JSON.stringify(source("src/bot/skins.ts"))};
export { radiusAtAngle } from ${JSON.stringify(source("src/bot/shape.ts"))};
export { createRng } from ${JSON.stringify(source("src/bot/math.ts"))};`,
    resolveDir: fileURLToPath(vendor),
    loader: "ts",
  },
  bundle: true,
  format: "esm",
  platform: "node",
  write: false,
});
const { SHAPES, radiusAtAngle, createRng } = await import(
  `data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].contents).toString("base64")}`
);
const shapes = SHAPES.filter((shape) => shape.id !== "goutte");
const metadata = JSON.parse(
  await readFile(new URL("materials/sprites.json", vendor), "utf8"),
);
if (shapes.map((shape) => shape.id).join() !== metadata.shapes.join()) {
  throw new Error("粒子身体与图集的形状顺序不一致");
}

// 对球内均匀取样而非把圆点铺在表面，投影后的核心自然比轮廓浓密。
const random = createRng(0x434c4f55);
const points = Array.from({ length: 48000 }, () => {
  let x, y, z;
  do {
    x = random() * 2 - 1;
    y = random() * 2 - 1;
    z = random() * 2 - 1;
  } while (x * x + y * y + z * z > 1);
  const front = (z + 1) / 2;
  const light = Math.max(
    0,
    Math.min(1, 0.3 + front * 0.56 - x * 0.26 - y * 0.34),
  );
  const size = 0.45 + random() * 0.4;
  return {
    x,
    y,
    z,
    gray: Math.min(255, Math.round(Math.round(45 + light * 210) / 8) * 8),
    alpha: Math.round((0.62 + front * 0.3) * 8) / 8,
    diameter: size < 0.6 ? 1.15 : size < 0.73 ? 1.5 : 1.8,
  };
}).sort((a, b) => a.z - b.z);
const compact = (value) => Number(value.toFixed(1));
const { width, height } = metadata.materials.particles;
const parts = [
  `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 1264 948" fill="none" stroke-linecap="round">`,
  "<!-- Generated by node vendor/bloub/tools/generate-particle-atlas.mjs; do not edit. -->",
];
for (const [index, shape] of shapes.entries()) {
  const bins = new Map();
  for (const point of points) {
    const radius =
      radiusAtAngle(shape.radii, Math.atan2(point.y, point.x)) * 100;
    const x = compact(point.x * radius);
    const y = compact(point.y * radius);
    const depth = Math.min(3, Math.floor((point.z + 1) * 2));
    const key = `${depth}|${point.gray}|${point.alpha}|${point.diameter}`;
    let bin = bins.get(key);
    if (!bin) bins.set(key, (bin = { ...point, path: "" }));
    bin.path += `M${x} ${y}h.01`;
  }
  parts.push(
    `<g id="shape-${shape.id}" transform="translate(${(index % 4) * 316 + 158} ${Math.floor(index / 4) * 316 + 158})">`,
  );
  for (const bin of bins.values()) {
    const gray = bin.gray.toString(16).padStart(2, "0").repeat(3);
    parts.push(
      `<path d="${bin.path}" stroke="#${gray}" stroke-opacity="${bin.alpha}" stroke-width="${bin.diameter}"/>`,
    );
  }
  parts.push("</g>");
}
parts.push("</svg>\n");
const svg = parts.join("");
const output = new URL("materials/body-particles.svg", vendor);
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8")) !== svg)
    throw new Error("粒子图集需要重新生成");
  process.stdout.write("粒子图集与生成命令一致\n");
} else {
  await writeFile(output, svg);
  process.stdout.write(
    `已生成 ${fileURLToPath(output)} (${Buffer.byteLength(svg)} bytes)\n`,
  );
}
